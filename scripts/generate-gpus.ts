import { writeFileSync } from 'node:fs'
import { GpuFamily, GpuVendor } from '../src/domain/gpu.ts'
import { mesaChipsets, withFloor, type Device, crocusFamily, irisFamily, amdgpuIds, nvidiaIds, tableOf } from './gpu-sources.ts'

const sources = {
  mesa: '2d0ec19dc8874e98860c1b1e506e18b1942e623f',
  linux: 'v7.2',
  pciids: '6b9987960d8d7e8cb87d2fcea0984e82b7e505f8',
} as const

const target = new URL('../src/server/gpu/families.generated.ts', import.meta.url)

const download = async (url: string) => {
  const r = await fetch(url)
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`)
  return r.text()
}
const mesa = (file: string) =>
  download(`https://gitlab.freedesktop.org/mesa/mesa/-/raw/${sources.mesa}/include/pci_ids/${file}_pci_ids.h`).then((t) => mesaChipsets(t, file))

const [crocus, iris, i915, i830, r300, r600, amdgpu, pciids] = await Promise.all([
  mesa('crocus'),
  mesa('iris'),
  mesa('i915'),
  mesa('i830'),
  mesa('r300'),
  mesa('r600'),
  download(`https://raw.githubusercontent.com/torvalds/linux/${sources.linux}/drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c`),
  download(`https://raw.githubusercontent.com/pciutils/pciids/${sources.pciids}/pci.ids`),
])

const devices: ReadonlyArray<Device> = [
  ...withFloor('crocus', 90, crocus).map((c) => ({ vendor: '8086', device: c.device, family: crocusFamily(c.token) }) as const),
  ...withFloor('iris', 280, iris).map((c) => ({ vendor: '8086', device: c.device, family: irisFamily(c.token) }) as const),
  ...withFloor('i915+i830', 14, [...i915, ...i830]).map((c) => ({ vendor: '8086', device: c.device, family: 'intel_gen5_o_anterior' }) as const),
  ...withFloor('r300+r600', 500, [...r300, ...r600]).map((c) => ({ vendor: '1002', device: c.device, family: 'amd_terascale_o_anterior' }) as const),
  ...withFloor('amdgpu_drv.c', 280, amdgpuIds(amdgpu)),
  ...withFloor('pci.ids 10de', 1400, nvidiaIds(pciids)),
]
const table = tableOf(devices)

const block = GpuVendor.literals
  .map((v) => {
    const families = GpuFamily.literals.flatMap((f) => {
      const ids = table[v][f]
      return ids === undefined ? [] : [`      ${f}: '${ids}',`]
    })
    return `    '${v}': {\n${families.join('\n')}\n    },`
  })
  .join('\n')

writeFileSync(
  target,
  `// GENERATED by scripts/generate-gpus.ts (pnpm gpu:generate). Do not edit by hand.
// Mesa ${sources.mesa}: include/pci_ids/{crocus,iris,i915,i830,r300,r600}_pci_ids.h
// Linux ${sources.linux}: drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c
// pciutils/pciids ${sources.pciids}: pci.ids
import type { GpuFamily, GpuVendor } from '../../domain/gpu.ts'

export const gpuTable = {
  leakSentinel: 'OPENGAME_TABLA_GPU',
  ids: {
${block}
  } satisfies Record<GpuVendor, Partial<Record<GpuFamily, string>>>,
} as const
`,
)

const unique = new Map(devices.map((d) => [`${d.vendor}:${d.device}`, d.family]))
for (const f of GpuFamily.literals) console.log(`${f.padEnd(28)}${[...unique.values()].filter((u) => u === f).length}`)
console.log(`Wrote ${target.pathname}`)
